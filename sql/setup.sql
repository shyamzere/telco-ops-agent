--spending cap and warehouse:

USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE RESOURCE MONITOR TELCO_RM
  WITH CREDIT_QUOTA = 5 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

CREATE WAREHOUSE IF NOT EXISTS TELCO_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE TELCO_WH SET RESOURCE_MONITOR = TELCO_RM;

CREATE DATABASE IF NOT EXISTS TELCO_DB;
CREATE SCHEMA IF NOT EXISTS TELCO_DB.OPS;
USE WAREHOUSE TELCO_WH;
USE SCHEMA TELCO_DB.OPS;


--create fake data:

CREATE OR REPLACE TABLE SITES AS
SELECT SEQ4()+1 AS SITE_ID,
  'Site-' || LPAD(SEQ4()+1, 3, '0') AS SITE_NAME,
  ARRAY_CONSTRUCT('Auckland','Waikato','Wellington','Canterbury','Otago')[UNIFORM(0,4,RANDOM())]::STRING AS REGION,
  ARRAY_CONSTRUCT('4G','5G')[UNIFORM(0,1,RANDOM())]::STRING AS TECHNOLOGY
FROM TABLE(GENERATOR(ROWCOUNT => 60));

CREATE OR REPLACE TABLE INCIDENTS AS
SELECT SEQ4()+1 AS INCIDENT_ID,
  UNIFORM(1,60,RANDOM()) AS SITE_ID,
  ARRAY_CONSTRUCT('Low','Medium','High','Critical')[UNIFORM(0,3,RANDOM())]::STRING AS SEVERITY,
  ARRAY_CONSTRUCT('Power outage','Fibre cut','Congestion','Hardware fault','Software bug')[UNIFORM(0,4,RANDOM())]::STRING AS CAUSE,
  DATEADD('minute', -UNIFORM(0, 60*24*90, RANDOM()), CURRENT_TIMESTAMP()) AS START_TIME,
  UNIFORM(5, 600, RANDOM()) AS DURATION_MINUTES
FROM TABLE(GENERATOR(ROWCOUNT => 3000));

CREATE OR REPLACE TABLE TICKETS AS
SELECT SEQ4()+1 AS TICKET_ID,
  UNIFORM(1,60,RANDOM()) AS SITE_ID,
  ARRAY_CONSTRUCT('No signal','Slow data','Dropped calls','Billing','SMS issue')[UNIFORM(0,4,RANDOM())]::STRING AS CATEGORY,
  DATEADD('minute', -UNIFORM(0, 60*24*90, RANDOM()), CURRENT_TIMESTAMP()) AS CREATED_AT,
  UNIFORM(10, 4000, RANDOM()) AS RESOLUTION_MINUTES
FROM TABLE(GENERATOR(ROWCOUNT => 5000));

SELECT COUNT(*) FROM INCIDENTS;


--read-only role: (so dosent add or delete which can be risky for an agent to access)

CREATE ROLE IF NOT EXISTS AGENT_READONLY;
GRANT USAGE ON WAREHOUSE TELCO_WH TO ROLE AGENT_READONLY;
GRANT USAGE ON DATABASE TELCO_DB TO ROLE AGENT_READONLY;
GRANT USAGE ON SCHEMA TELCO_DB.OPS TO ROLE AGENT_READONLY;
GRANT SELECT ON ALL TABLES IN SCHEMA TELCO_DB.OPS TO ROLE AGENT_READONLY;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELCO_DB.OPS TO ROLE AGENT_READONLY;
GRANT ROLE AGENT_READONLY TO USER "shyamzere";


